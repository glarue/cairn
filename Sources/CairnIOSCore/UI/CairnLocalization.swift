import SwiftUI
import CairnCore

/// Central localization manager for Cairn.
/// Supports English and Simplified Chinese, with automatic system fallback
/// or user-pinned language preference from Settings.
public enum CairnL10n {

    /// Active language setting. Synchronized from `CairnSettings.appLanguage`.
    nonisolated(unsafe) public static var currentLanguage: AppLanguage = .system

    /// Whether Simplified Chinese should currently be rendered.
    public static var isChinese: Bool {
        switch currentLanguage {
        case .chineseSimplified:
            return true
        case .english:
            return false
        case .system:
            let preferred = Locale.preferredLanguages.first?.lowercased() ?? ""
            return preferred.hasPrefix("zh")
        }
    }

    /// Current Locale corresponding to the active language.
    public static var currentLocale: Locale {
        isChinese ? Locale(identifier: "zh_Hans_CN") : Locale(identifier: "en_US")
    }

    /// Translate a key into the active language.
    public static func text(_ key: String) -> String {
        guard isChinese else { return key }
        if let direct = dictionary[key] {
            return direct
        }
        let trimmed = key.trimmingCharacters(in: .whitespacesAndNewlines)
        if let trimmedMatch = dictionary[trimmed] {
            return trimmedMatch
        }
        return key
    }

    /// Format a localized format string with arguments.
    public static func format(_ key: String, _ args: CVarArg...) -> String {
        let pattern = text(key)
        return String(format: pattern, arguments: args)
    }

